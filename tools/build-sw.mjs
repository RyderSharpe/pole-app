#!/usr/bin/env node
// Rewrites the generated block in sw.js: the version, and the list of files the phone must store
// with a fingerprint for each one.
//
//   node tools/build-sw.mjs          rewrite sw.js
//   node tools/build-sw.mjs --check  change nothing; exit with an error if sw.js is out of date
//
// Run it after changing any file the app uses. Phones only notice an update when sw.js changes.

import { readFile, writeFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Everything the app needs on the phone. Tests, tools and notes are left out.
const TOP_FILES = ['index.html', 'styles.css', 'manifest.webmanifest'];
const FOLDERS = ['src', 'fonts', 'icons'];

const BEGIN = '/* BEGIN GENERATED by tools/build-sw.mjs. Do not edit by hand. */';
const END = '/* END GENERATED */';

async function walk(root, folder) {
  const out = [];
  const entries = await readdir(path.join(root, folder), { withFileTypes: true });
  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue;
    const relative = folder + '/' + entry.name;
    if (entry.isDirectory()) out.push(...(await walk(root, relative)));
    else if (entry.isFile()) out.push(relative);
  }
  return out;
}

/** The files to store, sorted, with forward slashes. */
export async function listFiles(root = ROOT) {
  const files = [...TOP_FILES];
  for (const folder of FOLDERS) files.push(...(await walk(root, folder)));
  return files.sort();
}

const sha256 = (data) => createHash('sha256').update(data).digest('hex');

function splitWorker(text) {
  const start = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (start < 0 || end < 0 || end < start) throw new Error('sw.js has lost its BEGIN GENERATED / END GENERATED markers.');
  return { before: text.slice(0, start), after: text.slice(end + END.length) };
}

/** Works out the generated block for the files as they are now. Returns { block, version, files }. */
export async function generatedBlock(root = ROOT) {
  const files = await listFiles(root);
  const config = await readFile(path.join(root, 'src/config.js'), 'utf8');
  const found = /APP_VERSION\s*=\s*'([^']+)'/.exec(config);
  if (!found) throw new Error('APP_VERSION was not found in src/config.js.');

  const entries = [];
  const overall = createHash('sha256');
  for (const file of files) {
    const hash = sha256(await readFile(path.join(root, file)));
    entries.push([file, hash]);
    overall.update(file + '\0' + hash + '\n');
  }
  // The rest of sw.js counts too, so a change to how the offline copy works also makes a new version.
  const worker = splitWorker(await readFile(path.join(root, 'sw.js'), 'utf8'));
  overall.update(worker.before + '\0' + worker.after);

  const version = found[1] + '-' + overall.digest('hex').slice(0, 12);
  const lines = entries.map(([file, hash]) => "  ['" + file + "', '" + hash + "'],");
  const block = [BEGIN, "const VERSION = '" + version + "';", 'const FILES = [', ...lines, '];', END].join('\n');
  return { block, version, files };
}

/** Rewrites sw.js, or with check: true only reports. Returns { changed, version, files }. */
export async function rebuild(root = ROOT, options = {}) {
  const target = path.join(root, 'sw.js');
  const text = await readFile(target, 'utf8');
  const { before, after } = splitWorker(text);
  const { block, version, files } = await generatedBlock(root);
  const next = before + block + after;
  const changed = next !== text;
  if (changed && !options.check) await writeFile(target, next);
  return { changed, version, files };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  rebuild(ROOT, { check }).then(
    ({ changed, version, files }) => {
      if (check && changed) {
        console.error('sw.js is out of date. Run: npm run build');
        process.exit(1);
      }
      console.log((check ? 'sw.js is up to date: ' : changed ? 'sw.js rewritten: ' : 'sw.js already up to date: ') + version + ' (' + files.length + ' files)');
    },
    (error) => {
      console.error(error.message);
      process.exit(1);
    },
  );
}
