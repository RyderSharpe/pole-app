// Each copy of the app keeps its own store, named after the folder it is served from. Two copies
// under one web address (a "test" folder and a "real" folder, say) therefore never touch each other.
const SCOPE = self.registration.scope;
const PREFIX = 'polefield@' + new URL(SCOPE).pathname + '@';
const CACHE = PREFIX + VERSION;

const address = (file) => new URL(file, SCOPE).href;

async function fingerprint(buffer) {
  const digest = new Uint8Array(await crypto.subtle.digest('SHA-256', buffer));
  let hex = '';
  for (const byte of digest) hex += byte.toString(16).padStart(2, '0');
  return hex;
}

async function fetchChecked(file, expected) {
  // "reload" skips the browser's ordinary cache, so a new version never stores stale files.
  const response = await fetch(new Request(address(file), { cache: 'reload', credentials: 'same-origin' }));
  if (!response.ok) throw new Error(file + ' answered ' + response.status);
  const body = await response.arrayBuffer();
  if ((await fingerprint(body)) !== expected) throw new Error(file + ' does not match this version');
  const headers = new Headers();
  headers.set('Content-Type', response.headers.get('Content-Type') || 'application/octet-stream');
  headers.set('Content-Length', String(body.byteLength));
  return new Response(body, { status: 200, headers });
}

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const existed = await caches.has(CACHE);
      const cache = await caches.open(CACHE);
      try {
        // A few at a time: quick on a good connection, gentle on a weak one.
        const queue = FILES.slice();
        const worker = async () => {
          while (queue.length) {
            const [file, expected] = queue.shift();
            await cache.put(address(file), await fetchChecked(file, expected));
          }
        };
        await Promise.all([worker(), worker(), worker(), worker()]);
      } catch (error) {
        // All or nothing. A half-filled store must never be left behind. (If the store was
        // already there, it belongs to this same version and every file in it passed its check.)
        if (!existed) await caches.delete(CACHE);
        throw error;
      }
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      for (const name of await caches.keys()) {
        if (name.startsWith(PREFIX) && name !== CACHE) await caches.delete(name);
      }
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('message', (event) => {
  const type = event.data && event.data.type;
  if (type === 'SKIP_WAITING') self.skipWaiting();
  else if (type === 'GET_VERSION' && event.ports && event.ports[0]) event.ports[0].postMessage({ version: VERSION });
});

// Only the app's own address gets the app page. Any other address is looked up as a file.
function isAppPage(url) {
  const page = new URL(url);
  page.search = '';
  page.hash = '';
  return page.href === SCOPE || page.href === SCOPE + 'index.html';
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  if (!request.url.startsWith(SCOPE)) return;
  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      const stored = request.mode === 'navigate' && isAppPage(request.url) ? await cache.match(address('index.html')) : await cache.match(request, { ignoreSearch: true });
      if (stored) return stored;
      try {
        return await fetch(request);
      } catch (error) {
        return new Response('Not available without signal.', { status: 503, statusText: 'Offline', headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
      }
    })(),
  );
});
